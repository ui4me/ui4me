"""One version authority and a small, reviewable metadata synchronizer."""
from __future__ import annotations

import re
from pathlib import Path

from .common import ROOT, DevError, version


def replacements(value: str) -> dict[str, list[tuple[str, str]]]:
    return {
        "Cargo.toml": [(r'(?m)^version = "[^"]+"$', f'version = "{value}"')],
        "bindings/python/pyproject.toml": [(r'(?m)^version = "[^"]+"$', f'version = "{value}"')],
        "bindings/powershell/Ui4me/Ui4me.psd1": [(r"(?m)^    ModuleVersion = '[^']+'$", f"    ModuleVersion = '{value}'")],
        "bindings/powershell/Ui4me.Managed/Ui4me.Managed.csproj": [
            (r"<Version>[^<]+</Version>", f"<Version>{value}</Version>"),
            (r"<AssemblyVersion>[^<]+</AssemblyVersion>", f"<AssemblyVersion>{value}.0</AssemblyVersion>"),
            (r"<FileVersion>[^<]+</FileVersion>", f"<FileVersion>{value}.0</FileVersion>"),
        ],
    }


def generated(value: str) -> dict[str, str]:
    return {
        "bindings/python/src/ui4me/_version.py": '# Generated by python dev.py version --set; VERSION is authoritative.\n__version__ = "' + value + '"\n',
        "bindings/powershell/Ui4me.Managed/BuildVersion.cs": '// Generated by python dev.py version --set; VERSION is authoritative.\nnamespace Ui4me.Managed;\ninternal static class BuildVersion { internal const string Value = "' + value + '"; }\n',
    }


def synchronize(new_version: str | None = None, *, root: Path = ROOT) -> None:
    value = new_version if new_version is not None else (root / "VERSION").read_text(encoding="utf-8").strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", value):
        raise DevError("Use a stable three-part version. Prerelease mapping is not implemented.")
    expected: dict[str, str] = {}
    for relative, rules in replacements(value).items():
        current = (root / relative).read_text(encoding="utf-8")
        for pattern, replacement in rules:
            current, count = re.subn(pattern, replacement, current)
            if count != 1:
                raise DevError(f"Expected one version field matching {pattern!r} in {relative}; found {count}")
        expected[relative] = current
    expected.update(generated(value))
    mismatches = [relative for relative, content in expected.items()
                  if not (root / relative).is_file() or (root / relative).read_text(encoding="utf-8") != content]
    if new_version is None:
        if mismatches:
            raise DevError("Version metadata differs from VERSION: " + ", ".join(mismatches) + ". Run python dev.py version --set " + value)
        print("Version metadata consistent:", value)
        return
    for relative, content in expected.items():
        (root / relative).write_text(content, encoding="utf-8")
    (root / "VERSION").write_text(value + "\n", encoding="utf-8")
    print("Version metadata updated:", value)
